export let currentLang = localStorage.getItem('led_lang') || 'ru';

export function t(key) {
  return dict[currentLang][key] || key;
}

export function dbT(item, fieldName) {
  // item: object from DB, fieldName: 'notes' or 'bestUse' etc.
  const key = `${fieldName}_${currentLang}`;
  return item[key] || item[`${fieldName}_ru`] || ''; // fallback to ru if uk is missing
}

export function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('led_lang', lang);
  translatePage();
}

export function translatePage() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    // If it has children like SVG icons, we only want to replace text node.
    // Easiest is to put texts in <span> and add data-i18n to the span.
    if(el.tagName === 'INPUT' && el.type === 'text') {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });

  // Re-render calculators and wiki if needed
  if (window.updateCalc) window.updateCalc();
  if (window.renderSidebar) window.renderSidebar();
}

export function initI18n() {
  // Bind UI buttons
  const ruBtn = document.getElementById('lang_ru');
  const ukBtn = document.getElementById('lang_uk');
  
  if(ruBtn && ukBtn) {
    if(currentLang === 'ru') {
      ruBtn.classList.add('active');
      ukBtn.classList.remove('active');
    } else {
      ukBtn.classList.add('active');
      ruBtn.classList.remove('active');
    }

    ruBtn.addEventListener('click', () => {
      ruBtn.classList.add('active');
      ukBtn.classList.remove('active');
      setLang('ru');
    });
    
    ukBtn.addEventListener('click', () => {
      ukBtn.classList.add('active');
      ruBtn.classList.remove('active');
      setLang('uk');
    });
  }

  translatePage();
}
